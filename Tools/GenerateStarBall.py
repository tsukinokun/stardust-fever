"""玉の見た目の星形モデル（StardustFever/Assets/Models/StarBall.obj / .mtl）を作る。

    python Tools/GenerateStarBall.py

五芒星を、表と裏の中心を少し盛り上げた宝石のような立体にする（面ごとの平らな法線で、光がきらりと当たる）。
大きさは外側の先端が半径 OUTER_RADIUS。玉の Prefab で 1.5 倍され、当たり判定は半径 1.5 の球のまま
（星の先が釘に刺さって止まらないよう、物理は球で転がし、見た目だけ星にしている）。
面は外から見て反時計回り（Ball.obj と同じ向き）。
"""
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODELS = os.path.join(ROOT, "StardustFever", "Assets", "Models")

POINTS = 5
OUTER_RADIUS = 1.12   # 先端（球の半径 1.0 より少しだけ外へ出して、星だと分かるようにする）
INNER_RADIUS = 0.52   # 谷
APEX_HEIGHT = 0.5     # 表と裏の中心の盛り上がり
RIM_HEIGHT = 0.12     # 縁の厚みの半分（先端が紙のように薄く見えないようにする）


def sub(a, b):
    return (a[0] - b[0], a[1] - b[1], a[2] - b[2])


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def normalize(v):
    length = math.sqrt(sum(c * c for c in v)) or 1.0
    return (v[0] / length, v[1] / length, v[2] / length)


def main():
    rim = []
    for i in range(POINTS * 2):
        angle = math.pi / 2.0 + i * math.pi / POINTS  # 先端を真上から始める
        radius = OUTER_RADIUS if i % 2 == 0 else INNER_RADIUS
        rim.append((radius * math.cos(angle), radius * math.sin(angle)))

    front = (0.0, 0.0, APEX_HEIGHT)
    back = (0.0, 0.0, -APEX_HEIGHT)
    triangles = []
    count = len(rim)
    for i in range(count):
        x0, y0 = rim[i]
        x1, y1 = rim[(i + 1) % count]
        top0, top1 = (x0, y0, RIM_HEIGHT), (x1, y1, RIM_HEIGHT)
        bottom0, bottom1 = (x0, y0, -RIM_HEIGHT), (x1, y1, -RIM_HEIGHT)
        triangles.append((front, top0, top1))          # 表
        triangles.append((back, bottom1, bottom0))     # 裏
        triangles.append((top0, bottom0, bottom1))     # 縁
        triangles.append((top0, bottom1, top1))

    vertices = []
    normals = []
    faces = []
    for a, b, c in triangles:
        normal = normalize(cross(sub(b, a), sub(c, a)))
        # 外向き（星の中心から面の中心への向き）と逆なら裏返す
        center = ((a[0] + b[0] + c[0]) / 3.0, (a[1] + b[1] + c[1]) / 3.0, (a[2] + b[2] + c[2]) / 3.0)
        if sum(n * p for n, p in zip(normal, center)) < 0.0:
            b, c = c, b
            normal = (-normal[0], -normal[1], -normal[2])
        base = len(vertices)
        vertices.extend([a, b, c])
        normals.extend([normal, normal, normal])
        faces.append((base + 1, base + 2, base + 3))

    with open(os.path.join(MODELS, "StarBall.obj"), "w", encoding="utf-8", newline="\n") as f:
        f.write("# Generated by Tools/GenerateStarBall.py\nmtllib StarBall.mtl\no StarBall\n")
        for v in vertices:
            f.write(f"v {v[0]:.5f} {v[1]:.5f} {v[2]:.5f}\n")
        for n in normals:
            f.write(f"vn {n[0]:.5f} {n[1]:.5f} {n[2]:.5f}\n")
        f.write("usemtl StarBall\n")
        for a, b, c in faces:
            f.write(f"f {a}//{a} {b}//{b} {c}//{c}\n")

    with open(os.path.join(MODELS, "StarBall.mtl"), "w", encoding="utf-8", newline="\n") as f:
        # 金色の星。自己発光を 1 より上げてブルームでにじませ、淡い黄色の釘より明るく見せる
        f.write("newmtl StarBall\nKd 1.0 0.78 0.3\nKe 1.5 1.15 0.45\nNs 140\nd 1.0\n")
    print(f"wrote StarBall.obj: {len(vertices)} vertices, {len(faces)} faces")


if __name__ == "__main__":
    main()
