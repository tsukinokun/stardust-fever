"""入賞口の柱とチューリップの羽のモデル（StardustFever/Assets/Models/PocketPost*.obj / TulipWing.obj）を作る。

    python Tools/GeneratePocketModels.py

形は壁と同じ単位の箱（±1）で、Prefab の scale で伸ばす。色は MTL で入賞口ごとに変える
（スタート入賞口は金、チューリップは水色、星の門は桃色）。縁の光は各 Prefab の RimGlow で付ける。
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODELS = os.path.join(ROOT, "StardustFever", "Assets", "Models")

# 名前 → (Kd, Ke)
MATERIALS = {
    "PocketPostGold": ((1.0, 0.78, 0.25), (0.9, 0.65, 0.15)),
    "PocketPostCyan": ((0.25, 0.8, 0.95), (0.2, 0.6, 0.85)),
    "PocketPostPink": ((1.0, 0.45, 0.85), (0.85, 0.3, 0.7)),
    "TulipWing": ((0.35, 0.9, 1.0), (0.3, 0.75, 1.0)),
}


def main():
    # 壁のモデルの形（単位の箱）をそのまま使い、材質の名前だけ差し替える
    with open(os.path.join(MODELS, "Wall.obj"), encoding="utf-8") as f:
        box = [line for line in f if not line.startswith(("mtllib", "usemtl", "o ", "#"))]
    for name, (kd, ke) in MATERIALS.items():
        with open(os.path.join(MODELS, f"{name}.obj"), "w", encoding="utf-8", newline="\n") as f:
            f.write(f"# Generated by Tools/GeneratePocketModels.py\nmtllib {name}.mtl\no {name}\nusemtl {name}\n")
            f.writelines(box)
        with open(os.path.join(MODELS, f"{name}.mtl"), "w", encoding="utf-8", newline="\n") as f:
            f.write(f"newmtl {name}\nKd {kd[0]} {kd[1]} {kd[2]}\nKe {ke[0]} {ke[1]} {ke[2]}\nNs 64\nd 1.0\n")
        print(f"wrote {name}.obj")


if __name__ == "__main__":
    main()
